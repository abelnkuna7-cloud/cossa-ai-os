export type ModuleStatus =
  | "Planning"
  | "Design"
  | "Development"
  | "Testing"
  | "Live"
  | "Production";

export interface ModuleItem {
  title: string;
  to: string;
  icon: LucideIcon;
  status: ModuleStatus;
  tagline: string;
  description: string;
  value: string;
  benefits: string[];
  roadmap: string[];
}

export interface ModuleGroup {
  label: string;
  items: ModuleItem[];
}

const s = (
  title: string,
  to: string,
  icon: LucideIcon,
  status: ModuleStatus,
  tagline: string,
  description: string,
  value: string,
  benefits: string[],
  roadmap: string[],
): ModuleItem => {
  // A screen existing is not the same as a production integration existing.
  // Keep the navigation honest until each module has data, authorization,
  // evidence/audit logging and an end-to-end production test.
  const foundationRoutes = new Set([
    "/command-center",
    "/ai/cossa",
    "/sales/leads",
    "/sales/customers",
    "/sales/appointments",
    "/sales/quotations",
    "/operations/projects",
    "/operations/tasks",
  ]);

  return {
    title,
    to,
    icon,
    status: status === "Live" ? (foundationRoutes.has(to) ? "Testing" : "Development") : status,
    tagline,
    description,
    value,
    benefits,
    roadmap,
  };
};

